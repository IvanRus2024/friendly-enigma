def count_letters(text):
    # Создание словаря для хранения количества букв
    letter_count = {}

    # Прохождение по каждому символу в тексте
    for char in text:
        # Привидение символа к нижнему регистру
        lower_char = char.lower()
        # Проверка, является ли символ буквой
        if lower_char.isalpha():
            # Увеличение счетчика для данной буквы
            if lower_char in letter_count:
                letter_count[lower_char] += 1
            else:
                letter_count[lower_char] = 1

    return letter_count

# TODO Напишите функцию calculate_frequency

def calculate_frequency(letter_count):
    # Общая сумма букв
    total_letters = sum(letter_count.values())

    # Создание нового словаря для хранения частоты букв
    frequency = {}

    for letter, count in letter_count.items():
        # Вычисление частоты
        freq_value = count / total_letters if total_letters > 0 else 0
        # Форматирование значения до двух знаков после запятой
        frequency[letter] = f"{freq_value:.2f}"

    return frequency

